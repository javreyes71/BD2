-- 1. Tabla Region (Tabla Padre Principal)
CREATE TABLE Region (
    ID INT PRIMARY KEY,
    Nombre VARCHAR(100) NOT NULL,
    Superficie INT NOT NULL
);

-- 2. Tabla Provincia (Hija de Region)
CREATE TABLE Provincia (
    ID INT PRIMARY KEY,
    Nombre VARCHAR(100) NOT NULL,
    Superficie INT NOT NULL,
    ID_Region INT NOT NULL,
    FOREIGN KEY (ID_Region) 
    REFERENCES Region(ID) on update cascade
);

-- 3. Tabla Comuna (Hija de Provincia)
CREATE TABLE Comuna (
    ID INT PRIMARY KEY,
    Nombre VARCHAR(100) NOT NULL,
    Superficie INT NOT NULL,
    ID_Provincia INT NOT NULL,
    FOREIGN KEY (ID_Provincia) 
    REFERENCES Provincia(ID)  on update cascade
);

